const stroke=(id:string,path:Curve,width=6):ReferenceDecorationPath=>({id,width,profile:'round',curve:path});
function openPolyline(points:{x:number;y:number}[]):Curve{
  let length=0;
  const measured=points.map((point,index)=>{
    const previous=points[index-1];
    if(previous)length+=Math.hypot(point.x-previous.x,point.y-previous.y);
    return {...point,length};
  });
  return {points:measured,length};
}
